#!/usr/bin/env node
/**
 * Bake the front page's worked example from the model it claims to be.
 *
 * The homepage argues that a result can be checked, and the honest way to make
 * that argument is to show one — inputs, number, relation, assumptions, and the
 * boundary where it stops being valid. Typing those into the page by hand would
 * make the front door the one place on the site whose numbers nobody verifies,
 * and the first wrong exponent there costs more than having no example at all.
 *
 * So it is generated from `calculateTool` and the document, and `npm test`
 * fails if the committed file no longer matches what the model produces.
 *
 * Generated rather than computed in the browser for a second reason: importing
 * the evaluator into the route pulls every library document into the entry
 * chunk. `src/components/side-rail.tsx` carries the note about the last time
 * that happened.
 *
 * `axial` is the model on show because a reader can check it without a
 * calculator — 10 kN over 1000 mm² is 10 MPa — and because its boundary names
 * three specific things the number is not, which is the argument in a sentence.
 *
 *   node scripts/generate-home-demo.mjs          # write it
 *   node scripts/generate-home-demo.mjs --check  # fail if stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { calculateTool, initialInputs, toolFields } from "../src/lib/engineering.ts";
import { libraryDocuments } from "../src/lib/document-library.ts";
import { tools } from "../src/lib/catalog.ts";

const TOOL_ID = "axial";
const OUT = "src/lib/home-demo.generated.ts";

export function buildDemo() {
  const document = libraryDocuments[TOOL_ID];
  const tool = tools.find((item) => item.id === TOOL_ID);
  if (!document || !tool) throw new Error(`${TOOL_ID} is not in the library`);

  const inputs = initialInputs[TOOL_ID];
  const fields = toolFields[TOOL_ID] ?? [];
  const result = calculateTool(TOOL_ID, inputs);

  return {
    toolId: TOOL_ID,
    title: tool.title,
    // Symbols come from the document for inputs and from the evaluator for
    // outputs, where `quantitySymbol` already resolves σ, ε and ΔL. Showing
    // them makes the panel read as engineering rather than as a form.
    inputs: fields.map((field) => ({
      label: field.label,
      symbol: document.fields?.find((item) => item.id === field.key)?.symbol ?? "",
      value: String(inputs[field.key] ?? ""),
      unit: field.unit ?? "",
    })),
    outputs: result.values.map((value) => ({
      label: value.label,
      symbol: value.symbol ?? "",
      display: value.display,
      unit: value.unit,
    })),
    formula: document.formula,
    assumptions: document.assumptions ?? [],
    boundary: document.boundary,
    sourceLabel: document.sourceLabel,
    sourceUrl: document.sourceUrl,
  };
}

/**
 * The exact text the committed module must contain.
 * @param {ReturnType<typeof buildDemo>} demo
 */
export function renderDemoModule(demo) {
  return [
    "// Generated by scripts/generate-home-demo.mjs. Do not edit.",
    "//",
    `// The front page's worked example, taken from the ${TOOL_ID} model itself so`,
    "// the numbers on the door are the numbers the calculator produces.",
    "// `npm test` fails if this drifts.",
    "",
    "export type HomeDemo = {",
    "  toolId: string;",
    "  title: string;",
    "  inputs: { label: string; symbol: string; value: string; unit: string }[];",
    "  outputs: { label: string; symbol: string; display: string; unit: string }[];",
    "  formula: string;",
    "  assumptions: string[];",
    "  boundary: string;",
    "  sourceLabel: string;",
    "  sourceUrl: string;",
    "};",
    "",
    `export const homeDemo: HomeDemo = ${JSON.stringify(demo, null, 2)};`,
    "",
  ].join("\n");
}

// Only when invoked directly: the test imports the two functions above and must
// not write to the tree as a side effect of that import.
function main() {
  const file = renderDemoModule(buildDemo());
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== file) {
      console.error(`${OUT} is stale. Run: node scripts/generate-home-demo.mjs`);
      process.exit(1);
    }
    console.log("[home-demo] up to date");
    return;
  }
  writeFileSync(OUT, file);
  console.log(`[home-demo] wrote ${OUT}`);
}

if (process.argv[1]?.endsWith("generate-home-demo.mjs")) main();
